export function searchVerifiedFoods(query: string, categoryFilter?: string): VerifiedFoodItem[] {
  const clean = query.trim().toLowerCase();
  return verifiedFoodDatabase.filter((item) => {
    const matchesQuery = !clean || 
      item.name.toLowerCase().includes(clean) || 
      item.category.toLowerCase().includes(clean) ||
      (item.dietaryTags && item.dietaryTags.some(t => t.toLowerCase().includes(clean)));

    const matchesCategory = !categoryFilter || categoryFilter === 'All' || item.category === categoryFilter;

    return matchesQuery && matchesCategory;
  });
}

export function calculateCustomPortionMacros(
  food: VerifiedFoodItem, 
  grams: number
): { calories: number; protein: number; carbs: number; fat: number; fiber: number } {
  const ratio = Math.max(0.1, grams) / food.servingWeightGrams;
  return {
    calories: Math.round(food.calories * ratio),
    protein: Math.round(food.protein * ratio * 10) / 10,
    carbs: Math.round(food.carbs * ratio * 10) / 10,
    fat: Math.round(food.fat * ratio * 10) / 10,
    fiber: Math.round(food.fiber * ratio * 10) / 10,
  };
}
